/**
 * 扫描结果的**过期**文案（纯函数，不碰 React）。
 *
 * 为什么单独一层：过期的数字比没有数字更危险——它看起来是真的。
 * 用户保存文件后，面板上那行「4 条」与 `:42` 会一起悄悄变成假话，
 * 而界面上没有任何东西提示这件事。
 *
 * 所以这里的规矩是：
 *   ① 只有**真的写盘**（`diskChanged`）才标过期：没改动还报警，用户下次就不看这个提示了；
 *   ② 过期时**把旧数字撤掉**，不是加个角标继续显示——旧数字加上小字注释仍然会被读走；
 *   ③ 面板里保留列表（可能想对比改动前后），但明确说出「行号可能已偏移」。
 */

/** 面板顶部的过期提示：说明它为什么不可信，以及下一步点哪儿。 */
export const STALE_PANEL_NOTE =
  '这份列表是保存前的扫描结果：文件已经变了，行号与计数都可能偏移。'
  + '点右上角「重新扫描」拿新的，别拿这里的数字做判断。';

/** 右栏那一行的过期态：撤掉旧数字，只留动作。 */
export const STALE_RAIL_LABEL = '已修改 · 点此重新扫描';

/**
 * 保存之后要不要把扫描结果标记为过期。
 *
 * `diskChanged === false` 表示内容与磁盘一致（例如只是点了一下保存），
 * 这时候标过期就是假警——假警多了，真警就没人信。
 */
export function shouldInvalidateScans(diskChanged: boolean): boolean {
  return diskChanged === true;
}
